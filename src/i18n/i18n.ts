const resources = { "en-US": en, "zh-CN": zh } as const;

export interface I18nValue {
  locale: "zh-CN" | "en-US";
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
  formatNumber: (value: number) => string;
  formatDate: (value: number | Date, options?: Intl.DateTimeFormatOptions) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function useI18n(locale: AppLocale): I18nValue {
  const resolvedLocale = resolveLocale(locale);
  const t = useCallback((key: TranslationKey, params?: Record<string, string | number>) => {
    let value: string = resources[resolvedLocale][key] ?? resources["en-US"][key];
    for (const [name, replacement] of Object.entries(params ?? {})) {
      value = value.replaceAll(`{{${name}}}`, String(replacement));
    }
    return value;
  }, [resolvedLocale]);
  const formatNumber = useCallback(
    (value: number) => new Intl.NumberFormat(resolvedLocale).format(value),
    [resolvedLocale],
  );
  const formatDate = useCallback(
    (value: number | Date, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(resolvedLocale, options).format(value instanceof Date ? value : new Date(value)),
    [resolvedLocale],
  );
  return useMemo(
    () => ({ locale: resolvedLocale, t, formatNumber, formatDate }),
    [formatDate, formatNumber, resolvedLocale, t],
  );
}

export function I18nProvider({ locale, children }: { locale: AppLocale; children: ReactNode }) {
  const value = useI18n(locale);
  return createElement(I18nContext.Provider, { value }, children);
}

export function useAppI18n(): I18nValue {
  const context = useContext(I18nContext);
  const fallback = useI18n("system");
  return context ?? fallback;
}
